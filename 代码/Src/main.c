/* STM32F103C6 electronic password lock; original schematic pin mapping. */
#include "main.h"
#include "lcd1602.h"
#include "key4x4.h"
#include "buzzer.h"
#include "password_lock.h"

void SystemClock_Config(void);

int main(void)
{
    unsigned char key;
    HAL_Init();
    SystemClock_Config();
    Buzzer_Init();
    Key_Init();
    LCD_Init();
    Lock_Init();
    while (1)
    {
        Lock_Task();
        key = Key_Scan();
        if (key != 0) Lock_HandleKey(key);
        HAL_Delay(1);
    }
}

